#!/usr/bin/env node
/**
 * Writes src/sounds/samples.gen.ts from the Kenney recordings in src/sounds/kenney.
 * Each recording is trimmed to its audible span, faded out, loudness-matched, and embedded as base64 WAV,
 * so the cue needs no asset pipeline in either the desktop app or the website.
 * Requires ffmpeg on PATH: `pnpm --filter @pond/ui generate:sounds`.
 */
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const SOUNDS = join(import.meta.dirname, "../src/sounds");

/** Cue name → alternating recordings from Kenney's UI Audio pack (CC0), close in length, attack, and brightness. */
const SAMPLES = {
  tap: ["click4", "click5"],
  soft: ["rollover2", "click2"],
  toggleOn: ["switch5", "switch3"],
  toggleOff: ["switch4", "switch1"],
};

const SAMPLE_RATE = 44_100;
const SILENCE_DB = -50;
const FADE_OUT_S = 0.006;
/** Alternates are matched on mean level, since the same peak can hide a several-dB difference in body. */
const MEAN_DB = -25;
const PEAK_DB = -1;

/** Trims leading and trailing silence; the reversed fade-in is a fade-out that needs no known length. */
const TRIM = [
  `silenceremove=start_periods=1:start_threshold=${SILENCE_DB}dB`,
  "areverse",
  `silenceremove=start_periods=1:start_threshold=${SILENCE_DB}dB`,
  `afade=t=in:d=${FADE_OUT_S}`,
  "areverse",
].join(",");

function ffmpeg(args) {
  return execFileSync("ffmpeg", ["-v", "error", "-nostdin", ...args], {
    maxBuffer: 16 * 1024 * 1024,
  });
}

/** volumedetect reports on stderr, so the run is read from there. */
function measure(file) {
  const run = spawnSync(
    "ffmpeg",
    ["-nostdin", "-i", file, "-af", `${TRIM},volumedetect`, "-f", "null", "-"],
    { encoding: "utf8" },
  );
  const mean = /mean_volume: (-?[\d.]+) dB/.exec(run.stderr ?? "");
  const max = /max_volume: (-?[\d.]+) dB/.exec(run.stderr ?? "");
  if (run.status !== 0 || !mean || !max) {
    throw new Error(`ffmpeg could not measure ${file}: ${run.stderr}`);
  }
  return { mean: Number(mean[1]), max: Number(max[1]) };
}

/** Written to a file, not a pipe, so ffmpeg can seek back and fill in the WAV header's sizes. */
function render(name) {
  const file = join(SOUNDS, "kenney", `${name}.ogg`);
  const level = measure(file);
  const gain = Math.min(MEAN_DB - level.mean, PEAK_DB - level.max);
  const out = join(scratch, `${name}.wav`);
  ffmpeg([
    "-y",
    "-i",
    file,
    "-af",
    `${TRIM},volume=${gain.toFixed(2)}dB`,
    "-ac",
    "1",
    "-ar",
    String(SAMPLE_RATE),
    "-c:a",
    "pcm_s16le",
    "-map_metadata",
    "-1",
    "-fflags",
    "+bitexact",
    "-flags:a",
    "+bitexact",
    out,
  ]);
  const wav = readFileSync(out);
  const seconds = wav.readUInt32LE(40) / 2 / SAMPLE_RATE;
  return { wav, seconds };
}

const scratch = mkdtempSync(join(tmpdir(), "pond-sounds-"));
const lines = [
  "// Generated by packages/ui/scripts/generate-sound-samples.mjs from src/sounds/kenney. Do not edit.",
  "",
  "export interface SoundSample {",
  "  /** A mono 16-bit WAV, trimmed to its audible span and loudness-matched. */",
  "  wav: string;",
  "  seconds: number;",
  "}",
  "",
  "export const SOUND_SAMPLES = {",
];
for (const [cue, names] of Object.entries(SAMPLES)) {
  lines.push(`  ${cue}: [`);
  for (const name of names) {
    const { wav, seconds } = render(name);
    lines.push(
      "    {",
      `      wav: "${wav.toString("base64")}",`,
      `      seconds: ${Number(seconds.toFixed(4))},`,
      "    },",
    );
  }
  lines.push("  ],");
}
lines.push("} satisfies Record<string, ReadonlyArray<SoundSample>>;", "");

rmSync(scratch, { recursive: true });
writeFileSync(join(SOUNDS, "samples.gen.ts"), lines.join("\n"));
