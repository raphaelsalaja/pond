import {
  buildThemeTokens,
  type Gamut,
  HUE_NAMES,
  type ThemeInput,
  type ThemeMode,
} from "./tokens.ts";

/** Mirrors DEFAULT_LIGHT_THEME and DEFAULT_DARK_THEME in @pond/schema so the first paint matches the app defaults. */
export const DEFAULT_THEMES = {
  light: {
    accent: "#5E6AD2",
    background: "#ffffff",
    foreground: "#1B1B1B",
    contrast: 50,
  },
  dark: {
    accent: "#5E6AD2",
    background: "#0A0A0A",
    foreground: "#EEEEEE",
    contrast: 50,
  },
} as const satisfies Record<ThemeMode, ThemeInput>;

/** Light P3 must not outrank the dark sRGB block, so it skips dark roots explicitly. */
const SELECTORS = {
  light: ':root:not([data-theme="dark"]),\n[data-theme="light"]',
  dark: '[data-theme="dark"]',
} as const satisfies Record<ThemeMode, string>;

/** Photos, video, and color swatches look the same in every theme, so what sits on them stays fixed. */
const FIXED = {
  "--ds-media-foreground-primary": "oklch(1 0 0 / 0.81)",
  "--ds-media-foreground-secondary": "oklch(1 0 0 / 0.59)",
  "--ds-media-surface-primary": "oklch(1 0 0 / 0.07)",
  "--ds-media-surface-secondary": "oklch(1 0 0 / 0.135)",
  "--ds-media-surface-tertiary": "oklch(1 0 0 / 0.285)",
  "--ds-media-border": "oklch(1 0 0 / 0.435)",
  "--ds-media-edge": "oklch(0 0 0 / 0.36)",
  "--ds-media-background": "oklch(0 0 0 / 0.68)",
  "--ds-scrim": "light-dark(oklch(0 0 0 / 0.25), oklch(0 0 0 / 0.4))",
  "--ds-sheen": "linear-gradient(oklch(1 0 0 / 0.07), oklch(1 0 0 / 0.03))",
} as const;

const HEADER =
  "/* GENERATED by packages/theme/src/colors/gen.ts. Do not edit by hand.\n" +
  "   Edit packages/theme/src/colors/tokens.ts or ramps.ts, then run `pnpm --filter @pond/theme generate`. */\n";

type Entries = [string, string][];

const isScaleToken = (name: string) =>
  !HUE_NAMES.some(
    (hue) => name === `--ds-${hue}` || name.startsWith(`--ds-${hue}-`),
  );

function entries(mode: ThemeMode, gamut: Gamut, scale: boolean): Entries {
  return Object.entries(
    buildThemeTokens(DEFAULT_THEMES[mode], gamut).tokens,
  ).filter(([name]) => isScaleToken(name) === scale);
}

function block(selector: string, lines: string[], indent = ""): string {
  const head = selector
    .split("\n")
    .map((part) => `${indent}${part}`)
    .join("\n");
  const body = lines
    .map((line) => (line ? `${indent}  ${line}` : ""))
    .join("\n");
  return `${head} {\n${body}\n${indent}}`;
}

const declare = ([name, value]: [string, string]) => `${name}: ${value};`;

function themeBlocks(scale: boolean): string {
  const srgb = (["light", "dark"] as const).map((mode) =>
    block(SELECTORS[mode], entries(mode, "srgb", scale).map(declare)),
  );
  const p3 = (["light", "dark"] as const).map((mode) => {
    const base = new Map(entries(mode, "srgb", scale));
    const wide = entries(mode, "p3", scale).filter(
      ([name, value]) => base.get(name) !== value,
    );
    return block(SELECTORS[mode], wide.map(declare), "  ");
  });
  return `${srgb.join("\n\n")}\n\n@media (color-gamut: p3) {\n${p3.join("\n\n")}\n}`;
}

export function buildColorsCss(): string {
  const fixed = Object.entries(FIXED).map(declare);
  return `${HEADER}\n${block(":root", fixed)}\n\n${themeBlocks(false)}\n`;
}

export function buildTokensCss(): string {
  return `${HEADER}\n${themeBlocks(true)}\n`;
}
